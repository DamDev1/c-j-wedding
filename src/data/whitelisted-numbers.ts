/**
 * Normalizes user input phone numbers into 11-digit Nigerian format:
 * - strips all spaces, dashes, parentheses
 * - converts +234XXXXXXXXXX or 234XXXXXXXXXX to 0XXXXXXXXXX
 */
export function normalizePhoneNumber(raw: string): string {
  if (!raw) return "";
  let cleaned = raw.replace(/\D/g, "");

  // If starts with 234 (e.g. 2348012345678) and is 13 digits
  if (cleaned.startsWith("234") && cleaned.length === 13) {
    cleaned = "0" + cleaned.slice(3);
  }

  return cleaned;
}
